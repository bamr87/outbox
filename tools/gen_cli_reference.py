#!/usr/bin/env python3
"""Generate docs/reference/cli.md from the argparse parser in src/outbox/cli.py.

    python3 tools/gen_cli_reference.py --write    # rewrite docs/reference/cli.md
    python3 tools/gen_cli_reference.py --check    # exit 1 when it is stale

The subcommands, their flags, defaults and help strings live in one place,
`outbox.cli.build_parser()`. This renders them into Markdown, so the CLI
reference is derived rather than hand-kept (fleet UPS-DOC-05), and
tests/test_docs.py fails when the committed file is stale. The tables are built
from the parser's actions, not from `--help` output, so the result does not
change between Python versions.

Stdlib only. Imports `outbox` from src/, so it runs before `pip install -e .`.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("docs") / "reference" / "cli.md"
HEADER = (
    "<!-- GENERATED by `python3 tools/gen_cli_reference.py --write` from "
    "outbox.cli.build_parser() — do not edit by hand -->"
)


def build_parser(root: Path) -> argparse.ArgumentParser:
    """The CLI's own parser, imported from the source tree."""
    src = str(root / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    from outbox.cli import build_parser as _build

    return _build()


def subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    """(name, help, subparser) for every subcommand, in declaration order."""
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {choice.dest: choice.help or "" for choice in action._choices_actions}
            return [(name, helps.get(name, ""), sub) for name, sub in action.choices.items()]
    return []


def flag(action: argparse.Action) -> str:
    names = ", ".join(action.option_strings) or action.dest
    if action.nargs == 0:
        return f"`{names}`"
    metavar = action.metavar or (action.dest.upper() if action.option_strings else action.dest)
    return f"`{names} {metavar}`"


def default(action: argparse.Action) -> str:
    if action.required or action.default in (None, argparse.SUPPRESS):
        return "—"
    return f"`{action.default}`"


def sentence(text: str) -> str:
    """A help string as a sentence: capitalised, one full stop."""
    text = (text or "").strip().rstrip(".")
    return text[:1].upper() + text[1:] + "." if text else "—"


def cell(text: str) -> str:
    return (text or "—").replace("|", "\\|")


def render(parser: argparse.ArgumentParser) -> str:
    commands = subcommands(parser)
    lines = [
        HEADER,
        "",
        f"# {parser.prog} CLI reference",
        "",
        f"> Every `{parser.prog}` subcommand with its flags and defaults, generated from the "
        "argparse parser in `src/outbox/cli.py`.",
        "",
        f"Run each as `{parser.prog} <command>` (the installed script) or "
        "`python3 -m outbox.cli <command>`; `--help` on any of them prints the same flags.",
        "",
        "| Command | What it does |",
        "| --- | --- |",
    ]
    lines += [f"| [`{name}`](#{parser.prog}-{name}) | {cell(sentence(text))} |" for name, text, _ in commands]
    for name, text, sub in commands:
        options = [a for a in sub._actions if not isinstance(a, argparse._HelpAction)]
        lines += ["", f"## `{parser.prog} {name}`", "", sentence(text), ""]
        if not options:
            lines.append("No flags.")
            continue
        with_help = any(a.help for a in options)
        head = "| Flag | Required | Default |" + (" Help |" if with_help else "")
        lines += [head, "| --- | --- | --- |" + (" --- |" if with_help else "")]
        for a in options:
            row = f"| {flag(a)} | {'yes' if a.required else 'no'} | {default(a)} |"
            lines.append(row + (f" {cell(a.help or '')} |" if with_help else ""))
    return "\n".join(lines) + "\n"


def build(root: Path = ROOT) -> tuple[str | None, str]:
    """Return (the committed reference or None, a freshly rendered one)."""
    path = root / OUTPUT
    current = path.read_text(encoding="utf-8") if path.exists() else None
    return current, render(build_parser(root))


def is_current(root: Path = ROOT) -> bool:
    current, fresh = build(root)
    return current == fresh


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help=f"rewrite {OUTPUT}")
    mode.add_argument("--check", action="store_true", help=f"exit 1 when {OUTPUT} is stale")
    ap.add_argument("--root", type=Path, default=ROOT, help="repository root")
    args = ap.parse_args(argv)

    current, fresh = build(args.root)
    if args.check:
        if current != fresh:
            print(f"{OUTPUT} is stale: run `python3 tools/gen_cli_reference.py --write`", file=sys.stderr)
            return 1
        return 0
    if current != fresh:
        path = args.root / OUTPUT
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(fresh, encoding="utf-8")
        print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
